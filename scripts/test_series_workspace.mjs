import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';

const script = new URL('./series_workspace.mjs', import.meta.url).pathname;
assert.ok(fs.existsSync(script), 'Missing reusable series initialization/context/handoff command');
const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'comic-layout-test-')));
const hash = file => createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const run = (...args) => spawnSync(process.execPath, [script, ...args], {encoding: 'utf8'});
const write = (file, data) => { fs.mkdirSync(path.dirname(file), {recursive:true}); fs.writeFileSync(file, JSON.stringify(data, null, 2)); };
let cases = 0;
const pass = (result, reason) => { assert.equal(result.status, 0, `${reason}: ${result.stderr}`); cases++; return JSON.parse(result.stdout); };
const fail = (result, pattern) => { assert.notEqual(result.status, 0); assert.match(result.stderr, pattern); cases++; };
try {
  const initialized = pass(run('init', root, 'space-comic', '--title', 'Space Comic'), 'initialize new series');
  const dir = path.join(root, 'space-comic');
  const index = path.join(dir, 'series.json');
  const before = hash(index);
  const config = JSON.parse(fs.readFileSync(index));
  assert.equal(initialized.series_root, dir);
  assert.equal(config.active_chapter, null);
  assert.equal(config.resources.world_research.availability, 'planned');
  assert.ok(!fs.existsSync(path.join(dir, 'research/world-style.json')));
  assert.ok(!/status:\s*approved/.test(fs.readFileSync(path.join(dir, 'AGENTS.md'), 'utf8')));
  cases++;
  fail(run('init', root, 'space-comic'), /already exists/);
  assert.equal(hash(index), before); cases++;
  fail(run('init', root, '../foreign'), /series ID/);
  pass(run('check', index), 'pending scaffold is discoverable without fake approval');

  const source = path.join(dir, 'source/chapter-01.txt');
  fs.writeFileSync(source, 'Original canonical source');
  const chapterRoot = 'production/chapter-01';
  fs.mkdirSync(path.join(dir, chapterRoot, 'staging'), {recursive:true});
  fs.mkdirSync(path.join(dir, chapterRoot, 'qa'), {recursive:true});
  config.resources.source_01 = {path: 'source/chapter-01.txt', availability:'present', sha256:hash(source)};
  config.chapters['1'] = {root:chapterRoot, resources:{source:'source_01'}, next_action:'Research before design', blockers:['Research not reviewed']};
  config.active_chapter = 1;
  write(index, config);
  const checked = pass(run('check', index, '--chapter', '1'), 'resolve chapter paths');
  assert.equal(checked.resources.source.path, source);
  assert.equal(checked.resources.source.validator_argument, 'source/chapter-01.txt'); cases++;
  const job = {schema:'comic-job-v1', series_id:'space-comic', chapter:1, job_id:'render-01', owner:'worker', mode:'production', page_range:{first:1,last:3}, input_snapshot:[{resource_id:'source_01',sha256:hash(source)}], writes:[{path:`${chapterRoot}/staging/page-01-v1.png`,page:1}], report_path:`${chapterRoot}/qa/render-01.json`};
  const jobPath = path.join(dir, chapterRoot, 'jobs/render-01.json');
  write(jobPath, job);
  pass(run('check-jobs', index, jobPath), 'validate real snapshot and confined write paths');
  fs.writeFileSync(source, 'Changed source after dispatch');
  fail(run('check-jobs', index, jobPath), /hash|stale/i);
  config.resources.source_01.sha256 = hash(source); write(index, config);
  fail(run('check-jobs', index, jobPath), /snapshot|stale/i);
  job.input_snapshot[0].sha256 = hash(source); write(jobPath, job);
  const variant = structuredClone(job);
  variant.job_id = 'other'; variant.report_path = `${chapterRoot}/qa/other.json`;
  variant.writes = [{path:`${chapterRoot}/staging/page-02-v1.png`,page:2}];
  const otherPath = path.join(dir, chapterRoot, 'jobs/other.json');
  write(otherPath, variant);
  fail(run('check-jobs', index, jobPath, otherPath), /overlap/i);
  variant.mode = 'qa'; variant.writes = []; write(otherPath, variant);
  pass(run('check-jobs', index, jobPath, otherPath), 'reviewer may read overlapping pages but owns separate report');
  variant.mode = 'production'; variant.chapter = '1'; variant.writes = [{path:`${chapterRoot}/staging/page-02-v1.png`,page:2}]; write(otherPath, variant);
  fail(run('check-jobs', index, jobPath, otherPath), /chapter.*integer/i);
  variant.mode = 'qa'; variant.chapter = 1; variant.writes = [];
  variant.report_path = `${job.report_path}/nested.json`; write(otherPath, variant);
  fail(run('check-jobs', index, jobPath, otherPath), /overlap/i);
  config.resources.source_02 = {path:'source/chapter-02.txt',availability:'present',sha256:'a'.repeat(64)};
  config.chapters['2'] = {root:'production/chapter-02',resources:{source:'source_02'},next_action:'Import source',blockers:['Missing source']};
  write(index,config);
  pass(run('check', index, '--chapter','1'), 'unrelated chapter missing/stale files do not block selected context');
  fail(run('check', index, '--chapter','2'), /Missing resource/i);
  const foreignInput = structuredClone(job);
  foreignInput.input_snapshot.push({resource_id:'source_02',sha256:'a'.repeat(64)});
  write(otherPath,foreignInput);
  fail(run('check-jobs', index, otherPath), /Missing resource|snapshot/i);
  delete config.resources.source_02; delete config.chapters['2']; write(index,config);
  variant.report_path = `${chapterRoot}/qa/existing-file/nested.json`;
  fs.writeFileSync(path.join(dir,chapterRoot,'qa/existing-file'),'not a directory'); write(otherPath,variant);
  fail(run('check-jobs', index, otherPath), /ancestor.*directory/i);
  variant.report_path = `${chapterRoot}/qa/other.json`;
  variant.mode='production';
  fs.symlinkSync(path.join(root,'not-yet-created'),path.join(dir,chapterRoot,'staging/dangling'));
  variant.writes=[{path:`${chapterRoot}/staging/dangling/file.png`,page:1}]; write(otherPath,variant);
  fail(run('check-jobs', index, otherPath), /symlink/i);
  variant.mode='qa'; variant.writes=[];
  variant.report_path = job.report_path; write(otherPath, variant);
  fail(run('check-jobs', index, jobPath, otherPath), /overlap/i);
  variant.report_path = `${chapterRoot}/qa/other.json`; variant.mode = 'production';
  variant.writes = [{path:'production/manifests/chapter-01.json',page:1}]; write(otherPath, variant);
  fail(run('check-jobs', index, otherPath), /write scope/i);
  variant.writes = [{path:`${chapterRoot}/staging/page-04-v1.png`,page:4}]; write(otherPath, variant);
  fail(run('check-jobs', index, otherPath), /page range/i);
  variant.writes = [{path:`${chapterRoot}/staging/../../../../foreign/file.png`,page:1}]; write(otherPath, variant);
  fail(run('check-jobs', index, otherPath), /relative path/i);
  variant.writes = [{path:`${chapterRoot}/staging/link/file.png`,page:1}];
  fs.symlinkSync(root, path.join(dir, chapterRoot, 'staging/link')); write(otherPath, variant);
  fail(run('check-jobs', index, otherPath), /symlink|outside/i);
  config.resources.foreign = {path:'../other-series/source.txt',availability:'planned'}; write(index, config);
  fail(run('check', index), /relative path/i);
  delete config.resources.foreign;
  config.layout = 'mapped-v1'; config.validator_root = '..';
  config.directories.design = 'production';
  config.chapters['1'].qa = `${chapterRoot}/qa`;
  write(index, config);
  const legacy = pass(run('check', index, '--chapter', '1'), 'legacy mapping resolves workspace-root CLI paths');
  assert.equal(legacy.resources.source.validator_argument, 'space-comic/source/chapter-01.txt'); cases++;
  config.resources.source_01.availability = 'planned'; delete config.resources.source_01.sha256; write(index, config);
  fail(run('check', index), /planned.*exists/i);
  config.resources.source_01.availability = 'present'; config.resources.source_01.sha256 = hash(source);
  config.reader.publish_root = '../another-series/production'; write(index, config);
  fail(run('check', index), /publish.*reader/i);
  console.log(`Series workspace tests passed: ${cases} cases (real filesystem + CLI).`);
} finally { fs.rmSync(root, {recursive:true,force:true}); }
